struct Representation: Codable {
  let type: String
  let data: Data
}
struct Payload: Codable {
  let items: [[Representation]]
  var hash: String {
    var h = SHA256()
    for item in items {
      h.update(data: withUnsafeBytes(of: UInt64(item.count).bigEndian) { Data($0) })
      for r in item.sorted(by: { $0.type < $1.type }) {
        h.update(data: Data(r.type.utf8))
        h.update(data: withUnsafeBytes(of: UInt64(r.data.count).bigEndian) { Data($0) })
        h.update(data: r.data)
      }
    }
    return h.finalize().map { String(format: "%02x", $0) }.joined()
  }
}
