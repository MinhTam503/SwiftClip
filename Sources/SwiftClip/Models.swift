final class Settings: ObservableObject {
  static let shared = Settings()
  @Published var revision = 0
  private let d: UserDefaults
  init(defaults: UserDefaults = .standard) { d = defaults }
  func int(_ key: String, _ fallback: Int) -> Int {
    d.object(forKey: key) == nil ? fallback : d.integer(forKey: key)
  }
  func bool(_ key: String, _ fallback: Bool = false) -> Bool {
    d.object(forKey: key) == nil ? fallback : d.bool(forKey: key)
  }
  func string(_ key: String) -> String { d.string(forKey: key) ?? "" }
  func set(_ key: String, _ value: Any) {
    d.set(value, forKey: key)
    revision += 1
  }
  var limit: Int { int("limit", 500) }
  var maxBytes: Int { int("imageMB", 20) * 1024 * 1024 }
  var key: UInt32 { UInt32(int("key", 9)) }
  var modifiers: UInt32 { UInt32(int("modifiers", Int(cmdKey | shiftKey))) }
  static func validShortcut(key: UInt32, modifiers: UInt32) -> Bool {
    key <= 126 && modifiers & UInt32(cmdKey | controlKey | optionKey) != 0
  }
}
enum ClipboardReader {
  static let forbidden = [
    "org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType",
    "org.nspasteboard.AutoGeneratedType",
  ]
  static func kind(_ types: [String]) -> String {
    if types.contains(NSPasteboard.PasteboardType.fileURL.rawValue) { return "file" }
    if types.contains(NSPasteboard.PasteboardType.png.rawValue)
      || types.contains(NSPasteboard.PasteboardType.tiff.rawValue)
    {
      return "image"
    }
    if types.contains(NSPasteboard.PasteboardType.rtf.rawValue)
      || types.contains(NSPasteboard.PasteboardType.html.rawValue)
    {
      return "rich text"
    }
    if types.contains(NSPasteboard.PasteboardType.URL.rawValue) { return "url" }
    return "text"
  }
  static func read(_ pb: NSPasteboard, maxBytes: Int) -> (Payload, String, String)? {
    guard let entries = pb.pasteboardItems, !entries.isEmpty,
      !entries.contains(where: { item in forbidden.contains { item.types.contains(.init($0)) } })
    else { return nil }
    let allowed: [NSPasteboard.PasteboardType] = [
      .string, .URL, .fileURL, .png, .tiff, .rtf, .rtfd, .html,
    ]
    var total = 0
    var result = [[Representation]]()
    for item in entries {
      var reps = [Representation]()
      for type in allowed where item.types.contains(type) {
        guard let data = item.data(forType: type) else { continue }
        total += data.count
        guard total <= maxBytes else { return nil }
        reps.append(Representation(type: type.rawValue, data: data))
      }
      if !reps.isEmpty { result.append(reps) }
    }
    guard !result.isEmpty else { return nil }
    let types = result.flatMap { $0.map(\.type) }
    let kind = kind(types)
    let labels = entries.compactMap { item -> String? in
      if let file = item.string(forType: .fileURL), let url = URL(string: file) {
        return url.lastPathComponent + " " + file
      }
      return item.string(forType: .string) ?? item.string(forType: .URL)
    }
    var preview = labels.joined(separator: "\n")
    if preview.isEmpty, let data = entries.first?.data(forType: .rtf),
      let attributed = NSAttributedString(rtf: data, documentAttributes: nil)
    {
      preview = attributed.string
    }
    // Generic preview labels are rendered in the current UI language, not persisted.
    return (Payload(items: result), kind, preview)
  }
}

/// Local shortcuts must leave printable keys and essential navigation available to search.
enum PopupShortcut {
  static let mask: NSEvent.ModifierFlags = [.command, .option, .control, .shift]
  static func valid(key: UInt16, flags: NSEvent.ModifierFlags, search: Bool) -> Bool {
    let flags = flags.intersection(mask)
    guard key <= 126, ![53, 125, 126].contains(key) else { return false }
    if flags.isEmpty {
      return !search
        && [
          36, 76, 115, 119, 116, 121, 122, 120, 99, 118, 96, 97, 98, 100, 101, 109, 103, 111, 105,
          107, 113, 106, 64, 79, 80, 90,
        ].contains(key)
    }
    guard !flags.intersection([.command, .option, .control]).isEmpty else { return false }
    return !(key == 51 && flags == .command)
  }
}
